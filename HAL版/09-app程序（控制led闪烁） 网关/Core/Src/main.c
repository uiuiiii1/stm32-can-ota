/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_CAN_Init();
  MX_USART1_UART_Init();
  MX_SPI1_Init();
  /* USER CODE BEGIN 2 */

  //初始化更新模块（内部会初始化CAN并进入等待指令状态）
  APP_update_init();
  printf("CAN started\r\n");
  //W25Q80 上电自检：无论成败都打印读到的原始 JEDEC ID，便于排查接线
  //（0x000000=MISO无响应/未选中  0xFFFFFF=MISO悬空  0xEF4014=正确  其他值=型号不同或时序错乱）
  {
    uint32_t w25_id = 0;
    uint8_t w25_ret = W25Q80_ReadID(&w25_id);
    printf("W25Q80 JEDEC ID: 0x%06X (ret=%d)\r\n", (unsigned)w25_id, w25_ret);
    if (W25Q80_Init() == W25Q80_OK)
    {
      printf("W25Q80 ok\r\n");
    }
    else
    {
      printf("W25Q80 init failed! check wiring/CS\r\n");
    }
  }

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  uint8_t led_step = 0;
  while (1)
  {
    //==== 2026-09-27 晚的临时 CAN 链路诊断段已删除（实测定位为 CAN 模块电源线脱落），
    //==== 诊断方法留档：轮询 FIFO0 + 打印 StdId/DLC/8字节原始数据 + 每秒 alive 心跳 ====

    APP_update_work_cmd();
    led_step++;
    if (led_step >= 3)
    {
      led_step = 0;
    }
    //10ms 主循环节拍：串口收 bin 需要每轮排水环形缓冲（9600 波特率约 10ms 来 1 字节），
    //原来 1s 一轮会让 1KB 缓冲溢出丢数据；CAN 轮询因此变成 10ms 一次，响应也更灵敏
    HAL_Delay(10);
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

