#ifndef __APP_UPDATE_STORE_H
#define __APP_UPDATE_STORE_H

//==========================================================================
// 固件入库模块：串口收 bin → 存入网关自己的 W25Q80（元数据 + 正文）
//
// 镜像布局用 App_bootloader.h 里的约定：扇区0 放 8 字节元数据（大端：
// 4字节正文起始地址 + 4字节正文长度），正文从 APP_ADDR_MIN(0x1000) 开始。
//
// 上位机（串口助手）两步操作，中间必须等板子回话：
//   1) 发文本行  start:<镜像字节数>  （带换行）
//      板子校验长度、擦好扇区后回  ready
//   2) 看到 ready 后再用"发送文件"把 .bin 裸数据发过来（勿勾十六进制）
//   收完板子自动读回校验并写元数据：
//      成功回  done sum=0x... size=...
//      失败回  err:...（超时/校验错/读写错），重新从第 1 步再来即可
//
// 为什么中间要等 ready：擦扇区一次最长 400ms，而 9600 波特率没有流控，
// 如果擦除期间 PC 就开始灌数据，环形缓冲可能被冲爆；等 ready 的手工
// 握手把"擦除"和"收数据"在时间上隔开，1KB 缓冲就足够稳。
//==========================================================================

void App_update_store_init(void);   //初始化串口接收与状态机，上电调一次
void App_update_store_poll(void);   //主循环每轮调用（10ms 节拍）

#endif /* __APP_UPDATE_STORE_H */
