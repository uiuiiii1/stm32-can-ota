/**
  * @brief  TIM4 1ms 中断：清标志 + tick++、跑按键扫描、置长按请求标志。
  *         按键扫描放中断里是为了写 Flash 时主循环卡住也不影响按键计时。
  */
void TIM4_IRQHandler(void)
{
    Tick_ISR();                 // 清 Update 标志 + g_tick++

    Key_Tick();                 // 按键状态机推进

    // 按键松开就复位锁存，允许下一次长按再次生效
    if (!Key_Check(KEY_HOLD))
    {
        s_force_armed = 0;
    }

    // KEY_LONG = 按住满 2s；KEY_REPEAT = 长按后每 100ms 重复。两个事件都用来触发，
    // 加锁存保证一次长按只算一次
    if (Key_Check(KEY_LONG) || Key_Check(KEY_REPEAT))
    {
        if (!s_force_armed)
        {
            s_force_armed = 1;
            Key_Event_Flag = 1;   // 交给主循环去调 App_bootloader_reset()
        }
    }
}

