#ifndef __APP_BOOTLOADER_H
#define __APP_BOOTLOADER_H

//==========================================================================
// 网关（发送端）的固件镜像布局约定
//
// 网关的角色只是"固件仓库 + 发送机"：不跳转、不读按键、不挂 EEPROM，
// 那些是接收端 bootloader（07 工程）的活，相关代码已删，
// 原始版本在 07-bootloader程序/interface/ 里随时可查。
//
// 本头文件只保留"镜像在 W25 flash 里怎么摆放"的协议常量，供两处使用：
//   1) 把固件镜像写入网关自己的 W25Q80（元数据 + 正文）
//   2) APP_update_send_app() 按布局读出镜像并分帧发送
// 取值必须与 07 接收端的同名常量保持一致，改一处两边同步。
//==========================================================================

//W25 里的元数据（大端存放，写在镜像正文前面）：
//  0x00~0x03 = 镜像正文在 W25 里的起始地址
//  0x04~0x07 = 镜像总字节数
//注意：只有这 8 字节是大端；镜像正文是 .bin 裸数据，它的向量表是 Cortex-M 原生小端
#define META_APP_ADDR 0x00
#define META_APP_SIZE 8

//镜像合法性范围（都是 W25 地址空间的偏移，不能和内部 Flash 地址混比）
#define APP_SIZE_MAX 0x8000          //程序最大 32KB，等于接收端 app 区大小
#define APP_SIZE_MIN 500             //程序最小 500 字节
#define APP_ADDR_MIN 0x001000UL      //镜像最低从 0x1000 开始，0x000000 那一扇区放元数据
#define W25_FIRMWARE_END 0x0010000UL //固件区上限 64KB，与接收端约定一致（W25Q80 有 1MB，剩余留扩展）

#endif
